import type { Finding } from '../types/scan';
import SeverityBadge from './SeverityBadge';

interface FindingsTableProps {
  findings: Finding[];
}

export default function FindingsTable({ findings }: FindingsTableProps) {
  if (findings.length === 0) {
    return (
      <div className="card p-6 text-sm text-slate-400">
        No findings were generated by this scan.
      </div>
    );
  }

  return (
    <div className="card overflow-hidden">
      <div className="border-b border-slate-800 px-5 py-4">
        <h2 className="text-lg font-semibold text-white">Findings</h2>
      </div>
      <div className="overflow-x-auto">
        <table className="min-w-full divide-y divide-slate-800">
          <thead className="bg-slate-950/50 text-left text-xs uppercase tracking-wide text-slate-500">
            <tr>
              <th className="table-cell">Severity</th>
              <th className="table-cell">Finding</th>
              <th className="table-cell">Component</th>
              <th className="table-cell">Recommendation</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-800">
            {findings.map((finding, index) => (
              <tr key={`${finding.title}-${index}`} className="align-top">
                <td className="table-cell"><SeverityBadge severity={finding.severity} /></td>
                <td className="table-cell">
                  <p className="font-semibold text-white">{finding.title}</p>
                  <p className="mt-1 max-w-xl text-slate-400">{finding.description}</p>
                </td>
                <td className="table-cell text-slate-300">{finding.affected_component}</td>
                <td className="table-cell max-w-md text-slate-400">{finding.recommendation}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}
