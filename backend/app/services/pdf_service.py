from io import BytesIO
from datetime import datetime, timezone
from typing import Dict

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


class PDFGenerationError(Exception):
    pass


def generate_scan_pdf(scan: Dict) -> BytesIO:
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=0.75 * inch,
        leftMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.75 * inch,
    )

    story = []
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=20,
        textColor=colors.HexColor("#0f766e"),
        spaceAfter=12,
    )
    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Heading2"],
        fontName="Helvetica",
        fontSize=11,
        textColor=colors.HexColor("#334155"),
        spaceAfter=10,
    )
    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#0f172a"),
    )
    small_style = ParagraphStyle(
        "SmallBody",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#475569"),
    )

    story.append(Paragraph("SecureScan Dashboard", title_style))
    story.append(Paragraph("Professional Security Assessment Report", subtitle_style))
    story.append(Paragraph(f"Generated: {format_timestamp(scan.get('scan_date'))}", body_style))
    story.append(Paragraph(f"Target: {scan.get('target_url', 'Unknown')}", body_style))
    story.append(Paragraph(f"Risk Score: {scan.get('risk_score', 0)}", body_style))
    story.append(Paragraph(f"Security Grade: {scan.get('grade', 'F')}", body_style))
    story.append(Spacer(1, 0.2 * inch))

    story.append(Paragraph("Executive Summary", styles["Heading1"]))
    summary = scan.get("summary", {})
    story.append(Paragraph(
        f"This report summarizes the scan findings for {scan.get('target_url', 'the target')} and highlights the current security posture with actionable recommendations.",
        body_style,
    ))
    story.append(Spacer(1, 0.12 * inch))
    story.append(_build_summary_table(summary))
    story.append(Spacer(1, 0.2 * inch))

    story.append(Paragraph("Security Checks", styles["Heading1"]))
    story.append(_build_checks_table(scan.get("checks", {})))
    story.append(Spacer(1, 0.2 * inch))

    story.append(Paragraph("Detailed Findings", styles["Heading1"]))
    findings = scan.get("findings", [])
    if findings:
        for finding in findings:
            story.append(Paragraph(f"• {finding.get('title', 'Finding')}", styles["Heading2"]))
            story.append(Paragraph(f"Severity: {finding.get('severity', 'info').title()}", body_style))
            story.append(Paragraph(f"Description: {finding.get('description', 'No description provided.')}", body_style))
            story.append(Paragraph(f"Affected Component: {finding.get('affected_component', 'Unknown')}", body_style))
            story.append(Paragraph(f"Recommendation: {finding.get('recommendation', 'Review configuration.')}", body_style))
            story.append(Spacer(1, 0.1 * inch))
    else:
        story.append(Paragraph("No findings were generated during this scan.", body_style))
    story.append(Spacer(1, 0.2 * inch))

    story.append(Paragraph("Recommendations", styles["Heading1"]))
    recommendations = scan.get("recommendations", [])
    if recommendations:
        for index, recommendation in enumerate(recommendations, start=1):
            story.append(Paragraph(f"{index}. {recommendation}", body_style))
    else:
        story.append(Paragraph("No recommendations were generated.", body_style))
    story.append(Spacer(1, 0.25 * inch))

    story.append(Paragraph("Generated by SecureScan Dashboard", small_style))
    story.append(Paragraph("Educational & Defensive Security Tool", small_style))
    story.append(Paragraph(f"Timestamp: {format_timestamp(scan.get('scan_date'))}", small_style))
    story.append(Paragraph("Safety disclaimer: This report is intended for authorized, defensive security assessment only.", small_style))

    try:
        doc.build(story)
    except Exception as exc:
        raise PDFGenerationError(str(exc)) from exc

    buffer.seek(0)
    return buffer


def _build_summary_table(summary: Dict) -> Table:
    data = [
        ["Metric", "Count"],
        ["Total Findings", summary.get("total_findings", 0)],
        ["Critical", summary.get("critical", 0)],
        ["High", summary.get("high", 0)],
        ["Medium", summary.get("medium", 0)],
        ["Low", summary.get("low", 0)],
        ["Info", summary.get("info", 0)],
    ]
    table = Table(data, colWidths=[2.8 * inch, 1.0 * inch])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f766e")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("ALIGN", (1, 1), (-1, -1), "CENTER"),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.whitesmoke, colors.HexColor("#f8fafc")]),
    ]))
    return table


def _build_checks_table(checks: Dict) -> Table:
    rows = [
        ["Check", "Result"],
        ["SSL/TLS", _friendly_status(checks.get("ssl", {}))],
        ["Security Headers", _friendly_status(checks.get("headers", {}))],
        ["HTTPS Redirect", _friendly_status(checks.get("redirect", {}))],
        ["Server Information Leakage", _friendly_status(checks.get("server_leakage", {}))],
        ["Open Ports", _friendly_status(checks.get("ports", {}))],
        ["Frontend Library Detection", _friendly_status(checks.get("libraries", {}))],
        ["Cookie Security", _friendly_status(checks.get("cookies", {}))],
    ]
    table = Table(rows, colWidths=[2.8 * inch, 2.8 * inch])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f766e")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return table


def _friendly_status(payload: Dict) -> str:
    if not payload:
        return "Not checked"
    if payload.get("ok") is False:
        return payload.get("error") or "Failed"
    if payload.get("status"):
        return payload.get("status")
    return "Completed"


def format_timestamp(value: str | None) -> str:
    if not value:
        return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        return parsed.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    except ValueError:
        return str(value)
